#!/usr/bin/env node
// Lists every public symbol reachable from the package.json "exports" entry points.
// Used by test/unit/package/PublicApiReport.test.ts to pin the public surface:
// adding, removing, or deprecating an export must show up as a reviewed snapshot diff.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const repoRoot = resolve(fileURLToPath(new URL("..", import.meta.url)));

function entryPoints() {
  const pkg = JSON.parse(readFileSync(resolve(repoRoot, "package.json"), "utf8"));
  return Object.entries(pkg.exports)
    .filter(([, target]) => typeof target === "object" && typeof target.types === "string")
    .map(([subpath, target]) => ({
      subpath,
      source: resolve(repoRoot, target.types.replace(/^\.\/dist\//, "src/").replace(/\.d\.ts$/, ".ts"))
    }));
}

function symbolKind(symbol) {
  const f = symbol.flags;
  if (f & ts.SymbolFlags.Class) return "class";
  if (f & ts.SymbolFlags.Enum) return "enum";
  if (f & ts.SymbolFlags.Function) return "function";
  if (f & ts.SymbolFlags.Variable) return (f & ts.SymbolFlags.TypeAlias) || (f & ts.SymbolFlags.Interface) ? "const+type" : "const";
  if (f & ts.SymbolFlags.Interface) return "interface";
  if (f & ts.SymbolFlags.TypeAlias) return "type";
  if (f & ts.SymbolFlags.Module) return "namespace";
  return "unknown";
}

function hasDeprecatedTag(decl) {
  return !!decl && ts.getJSDocTags(decl).some((tag) => tag.tagName.text === "deprecated");
}

function isDeprecated(symbol) {
  return (symbol.declarations ?? []).some(hasDeprecatedTag);
}

function publicEntries() {
  const configPath = resolve(repoRoot, "tsconfig.json");
  const config = ts.readConfigFile(configPath, ts.sys.readFile);
  const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, repoRoot);
  const entries = entryPoints();
  const program = ts.createProgram({
    rootNames: entries.map((e) => e.source),
    options: { ...parsed.options, noEmit: true }
  });
  const checker = program.getTypeChecker();
  return entries.map(({ subpath, source }) => {
    const sourceFile = program.getSourceFile(source);
    if (!sourceFile) throw new Error(`entry source not found: ${source}`);
    const moduleSymbol = checker.getSymbolAtLocation(sourceFile);
    const exports = moduleSymbol ? checker.getExportsOfModule(moduleSymbol) : [];
    const symbols = exports.map((exported) => {
      const target = exported.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exported) : exported;
      const deprecated = isDeprecated(exported) || isDeprecated(target);
      return { name: exported.getName(), target, deprecated };
    });
    return { subpath, symbols, checker };
  });
}

export function buildPublicApiReport() {
  const lines = [
    "# Public API report (generated by scripts/api-report.mjs — do not edit by hand)",
    "# Update with: npx vitest run test/unit/package/PublicApiReport.test.ts -u",
    ""
  ];
  for (const { subpath, symbols } of publicEntries()) {
    const rows = symbols.map(({ name, target, deprecated }) => {
      return `${symbolKind(target).padEnd(10)} ${name}${deprecated ? "  @deprecated" : ""}`;
    });
    rows.sort((a, b) => a.slice(11).localeCompare(b.slice(11)));
    lines.push(`## ${subpath} (${rows.length})`, ...rows, "");
  }
  return lines.join("\n");
}

const format = ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.UseAliasDefinedOutsideCurrentScope;
const oneLine = (text) => text.replace(/[^\S\r\n]*[\r\n]+\s*/g, " ");
const modifiers = (decl) => decl ? ts.getCombinedModifierFlags(decl) : 0;
const hidden = ts.ModifierFlags.Private | ts.ModifierFlags.Protected;

function memberRows(checker, target, kind) {
  const rows = [];
  // Omitting the enclosing declaration keeps names independent of relative import paths.
  const typeText = (type, flags = format) => oneLine(checker.typeToString(type, undefined, flags));
  function signatures(type, signatureKind, prefix) {
    for (const sig of checker.getSignaturesOfType(type, signatureKind)) {
      if (!(modifiers(sig.declaration) & hidden)) {
        const suffix = hasDeprecatedTag(sig.declaration) ? "  @deprecated" : "";
        rows.push(prefix + oneLine(checker.signatureToString(sig, undefined, format)) + suffix);
      }
    }
  }
  function memberName(prop) {
    const name = (prop.valueDeclaration ?? prop.declarations?.[0])?.name;
    return name && ts.isComputedPropertyName(name) ? oneLine(name.getText()) : prop.name;
  }
  function members(type, prefix = "") {
    for (const index of checker.getIndexInfosOfType(type)) {
      rows.push(prefix + (index.isReadonly ? "readonly " : "") + "[key: " + typeText(index.keyType) + "]: " + typeText(index.type));
    }
    const properties = checker.getPropertiesOfType(type).slice().sort((a, b) => memberName(a).localeCompare(memberName(b), "en"));
    for (const prop of properties) {
      const decl = prop.valueDeclaration ?? prop.declarations?.[0];
      if (prop.flags & ts.SymbolFlags.Prototype || modifiers(decl) & hidden ||
          (decl?.name && ts.isPrivateIdentifier(decl.name))) continue;
      const readonly = modifiers(decl) & ts.ModifierFlags.Readonly ||
        ((prop.flags & ts.SymbolFlags.GetAccessor) && !(prop.flags & ts.SymbolFlags.SetAccessor));
      const label = prefix + (readonly ? "readonly " : "") + memberName(prop) + (prop.flags & ts.SymbolFlags.Optional ? "?" : "");
      const value = checker.getTypeOfSymbol(prop);
      if (prop.flags & ts.SymbolFlags.Method) {
        signatures(checker.getNonNullableType(value), ts.SignatureKind.Call, label);
      } else {
        const suffix = isDeprecated(prop) ? "  @deprecated" : "";
        rows.push(label + ": " + typeText(value) + suffix);
      }
    }
  }
  if (kind === "function") {
    signatures(checker.getTypeOfSymbol(target), ts.SignatureKind.Call, "");
  } else if (kind === "class") {
    const statics = checker.getTypeOfSymbol(target);
    signatures(statics, ts.SignatureKind.Construct, "new ");
    members(checker.getDeclaredTypeOfSymbol(target));
    members(statics, "static ");
  } else {
    if (kind.startsWith("const")) rows.push(": " + typeText(checker.getTypeOfSymbol(target)));
    if (["interface", "type", "const+type"].includes(kind)) {
      const type = checker.getDeclaredTypeOfSymbol(target);
      if ((type.flags & ts.TypeFlags.Object || type.isIntersection()) && !checker.isArrayType(type) && !checker.isTupleType(type)) {
        signatures(type, ts.SignatureKind.Call, "");
        signatures(type, ts.SignatureKind.Construct, "new ");
        members(type);
      } else {
        rows.push("= " + typeText(type, format | ts.TypeFormatFlags.InTypeAlias));
      }
    }
  }
  return rows.map((row) => "  " + row);
}

export function buildPublicApiMembersReport() {
  const lines = ["# Public API members (generated by scripts/api-report.mjs — do not edit by hand)", ""];
  for (const { subpath, symbols, checker } of publicEntries()) {
    if (subpath === ".") continue;
    lines.push("## " + subpath);
    for (const { name, target, deprecated } of symbols.sort((a, b) => a.name.localeCompare(b.name, "en"))) {
      const kind = symbolKind(target);
      lines.push(kind + " " + name + (deprecated ? "  @deprecated" : ""), ...memberRows(checker, target, kind));
    }
    lines.push("");
  }
  return lines.join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const report = buildPublicApiReport();
  const out = process.argv[2];
  if (out) writeFileSync(out, report);
  else process.stdout.write(report);
}
